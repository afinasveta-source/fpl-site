ALTER TABLE users DROP CONSTRAINT lr_users_deleted_not_public;
ALTER TABLE users ADD CONSTRAINT lr_users_deleted_not_public CHECK (
  deleted_at IS NULL
  OR NOT (public_profile OR public_city OR public_contacts OR public_works OR public_rating OR public_social)
