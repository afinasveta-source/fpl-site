ALTER TABLE support_threads ADD CONSTRAINT lr_support_thread_no UNIQUE (thread_no);
CREATE INDEX lr_support_threads_user ON support_threads (user_id, updated_at DESC);

------------------------------------------------------------------------
-- 4. Работа: черновик и сданные версии.
--    Черновик — версия без submitted_at, у работы не больше одного черновика.
--    Сданная версия неизменна: её текст, фото и время сдачи не меняются и не удаляются.
--    Работа ссылается (последняя / для конкурса / для диплома) только на сданные версии.
------------------------------------------------------------------------
ALTER TABLE submission_versions ADD CONSTRAINT lr_sv_final_matches
  CHECK (is_final_submit = (submitted_at IS NOT NULL));
CREATE UNIQUE INDEX lr_sv_one_draft ON submission_versions (submission_id) WHERE submitted_at IS NULL;

CREATE FUNCTION lr_sv_frozen() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.submitted_at IS NOT NULL THEN
      RAISE EXCEPTION 'a submitted version cannot be deleted';
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.submitted_at IS NOT NULL AND (
       NEW.submission_id, NEW.version_no, NEW.payload, NEW.source, NEW.is_final_submit, NEW.submitted_at, NEW.created_by)
       IS DISTINCT FROM
       (OLD.submission_id, OLD.version_no, OLD.payload, OLD.source, OLD.is_final_submit, OLD.submitted_at, OLD.created_by) THEN
    RAISE EXCEPTION 'a submitted version cannot change; submit a new version';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER lr_sv_frozen BEFORE UPDATE OR DELETE ON submission_versions
  FOR EACH ROW EXECUTE FUNCTION lr_sv_frozen();

CREATE FUNCTION lr_svm_frozen() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v uuid;
BEGIN
  FOR v IN SELECT unnest(ARRAY[
      CASE WHEN TG_OP IN ('UPDATE','DELETE') THEN OLD.submission_version_id END,
      CASE WHEN TG_OP IN ('INSERT','UPDATE') THEN NEW.submission_version_id END]) LOOP
    IF v IS NOT NULL AND EXISTS (SELECT 1 FROM submission_versions WHERE id = v AND submitted_at IS NOT NULL) THEN
      RAISE EXCEPTION 'files of a submitted version cannot change';
    END IF;
  END LOOP;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER lr_svm_frozen BEFORE INSERT OR UPDATE OR DELETE ON submission_version_media
  FOR EACH ROW EXECUTE FUNCTION lr_svm_frozen();

CREATE FUNCTION lr_submission_points_to_submitted() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM submission_versions v
             WHERE v.id IN (NEW.latest_version_id, NEW.competition_version_id, NEW.diploma_version_id)
               AND v.submitted_at IS NULL) THEN
    RAISE EXCEPTION 'a work can point only to submitted versions';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER lr_submission_points_to_submitted BEFORE INSERT OR UPDATE ON submissions
  FOR EACH ROW EXECUTE FUNCTION lr_submission_points_to_submitted();

COMMIT;
